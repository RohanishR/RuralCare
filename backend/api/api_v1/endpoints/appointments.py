@router.get(
    "/{appointment_id}",
    response_model=AppointmentResponse,
)
async def get_appointment(
    appointment_id: str,
    current_user: UserResponse = Depends(
        get_current_user
    ),
):
    appointment = await AppointmentModel.get_by_id(
        appointment_id
    )

    if not appointment:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Appointment not found.",
        )

    allowed = False

    if current_user.role == "admin":
        allowed = True

    elif current_user.role == "patient":
        patient = await get_patient_for_user(
            current_user.id
        )

        allowed = bool(
            patient
            and appointment["patient_id"]
            == str(patient["_id"])
        )

    elif current_user.role == "doctor":
        db = get_database()

        doctor = await db["doctors"].find_one(
            {"user_id": current_user.id}
        )

        allowed = bool(
            doctor
            and appointment["doctor_id"]
            == str(doctor["_id"])
        )

    if not allowed:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="You are not allowed to access this appointment.",
        )

    return await build_response(appointment)


@router.put(
    "/{appointment_id}",
    response_model=AppointmentResponse,
)
async def update_appointment(
    appointment_id: str,
    payload: AppointmentUpdate,
    current_user: UserResponse = Depends(
        get_current_user
    ),
):
    appointment = await AppointmentModel.get_by_id(
        appointment_id
    )

    if not appointment:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Appointment not found.",
        )

    db = get_database()

    doctor = await get_doctor(
        appointment["doctor_id"]
    )

    patient = await get_patient_for_user(
        current_user.id
    )

    is_patient = bool(
        current_user.role == "patient"
        and patient
        and appointment["patient_id"]
        == str(patient["_id"])
    )

    is_doctor = bool(
        current_user.role == "doctor"
        and doctor
        and doctor.get("user_id")
        == current_user.id
    )

    if not is_patient and not is_doctor and current_user.role != "admin":
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="You are not allowed to modify this appointment.",
        )

    update_data = payload.model_dump(
        exclude_unset=True
    )

    requested_status = update_data.get("status")

    if requested_status:
        if is_patient and requested_status not in {
            AppointmentStatus.cancelled.value,
            AppointmentStatus.rescheduled.value,
        }:
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail="Patients can only cancel or request rescheduling.",
            )

        if is_doctor and requested_status not in {
            AppointmentStatus.confirmed.value,
            AppointmentStatus.completed.value,
            AppointmentStatus.cancelled.value,
            AppointmentStatus.rescheduled.value,
        }:
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail="Invalid doctor appointment status.",
            )

    new_date = update_data.get(
        "appointment_date",
        appointment["appointment_date"],
    )

    new_time = update_data.get(
        "appointment_time",
        appointment["appointment_time"],
    )

    if "appointment_date" in update_data or "appointment_time" in update_data:
        if not is_patient and current_user.role != "admin":
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail="Only the patient can request a new appointment slot.",
            )

        if new_date < date.today():
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Appointment date must be today or later.",
            )

        if not availability_allows_slot(
            doctor.get("availability") if doctor else None,
            new_date,
            new_time,
        ):
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="The selected time is outside the doctor's availability.",
            )

        if await AppointmentModel.slot_is_taken(
            doctor_id=appointment["doctor_id"],
            appointment_date=new_date,
            appointment_time=new_time,
            exclude_id=appointment_id,
        ):
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail="The requested appointment slot is already booked.",
            )

        update_data["status"] = (
            AppointmentStatus.rescheduled.value
        )

    if (
        requested_status
        == AppointmentStatus.cancelled.value
        and appointment["status"]
        == AppointmentStatus.completed.value
    ):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="A completed appointment cannot be cancelled.",
        )

    if not update_data:
        return await build_response(appointment)

    try:
        updated = await AppointmentModel.update(
            appointment_id,
            update_data,
        )
    except DuplicateKeyError:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="The requested appointment slot is already booked.",
        )

    if not updated:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Appointment not found.",
        )

    return await build_response(updated)


@router.put(
    "/{appointment_id}/cancel",
    response_model=AppointmentResponse,
)
async def cancel_appointment(
    appointment_id: str,
    current_user: UserResponse = Depends(
        get_current_user
    ),
):
    appointment = await AppointmentModel.get_by_id(
        appointment_id
    )

    if not appointment:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Appointment not found.",
        )

    patient = await get_patient_for_user(
        current_user.id
    )

    allowed = bool(
        current_user.role == "patient"
        and patient
        and appointment["patient_id"]
        == str(patient["_id"])
    )

    if current_user.role == "doctor":
        doctor = await get_doctor(
            appointment["doctor_id"]
        )
        allowed = bool(
            doctor
            and doctor.get("user_id")
            == current_user.id
        )

    if current_user.role == "admin":
        allowed = True

    if not allowed:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="You are not allowed to cancel this appointment.",
        )

    if appointment["status"] == "completed":
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="A completed appointment cannot be cancelled.",
        )

    updated = await AppointmentModel.update(
        appointment_id,
        {
            "status": AppointmentStatus.cancelled.value
        },
    )

    return await build_response(updated)


@router.put(
    "/{appointment_id}/complete",
    response_model=AppointmentResponse,
)
async def complete_appointment(
    appointment_id: str,
    current_user: UserResponse = Depends(
        require_doctor
    ),
):
    appointment = await AppointmentModel.get_by_id(
        appointment_id
    )

    if not appointment:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Appointment not found.",
        )

    doctor = await get_doctor(
        appointment["doctor_id"]
    )

    if not doctor or doctor.get("user_id") != current_user.id:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="You are not allowed to complete this appointment.",
        )

    if appointment["status"] == "cancelled":
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="A cancelled appointment cannot be completed.",
        )

    updated = await AppointmentModel.update(
        appointment_id,
        {
            "status": AppointmentStatus.completed.value
        },
    )

    return await build_response(updated)


@router.delete(
    "/{appointment_id}",
    status_code=status.HTTP_204_NO_CONTENT,
)
async def delete_appointment(
    appointment_id: str,
    current_user: UserResponse = Depends(
        get_current_user
    ),
):
    appointment = await AppointmentModel.get_by_id(
        appointment_id
    )

    if not appointment:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Appointment not found.",
        )

    patient = await get_patient_for_user(
        current_user.id
    )

    allowed = bool(
        current_user.role == "patient"
        and patient
        and appointment["patient_id"]
        == str(patient["_id"])
    )

    if current_user.role == "admin":
        allowed = True

    if not allowed:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="You are not allowed to delete this appointment.",
        )

    if appointment["status"] != "cancelled":
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Only cancelled appointments can be deleted.",
        )

    await AppointmentModel.delete(
        appointment_id
    )
