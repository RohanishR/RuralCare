def serialize_appointment(
    appointment: dict,
    doctor: Optional[dict] = None,
) -> dict:
    result = dict(appointment)

    result["id"] = str(result.pop("_id"))

    if doctor:
        result["doctor_name"] = doctor.get("name")
        result["doctor_specialization"] = doctor.get(
            "specialization"
        )
        result["consultation_fee"] = doctor.get(
            "consultation_fee"
        )

    return result


def parse_time(value: str):
    try:
        return datetime.strptime(value, "%H:%M").time()
    except ValueError:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Appointment time must use HH:MM format.",
        )


def get_day_name(appointment_date: date) -> str:
    return appointment_date.strftime("%A").lower()


def availability_allows_slot(
    availability,
    appointment_date: date,
    appointment_time: str,
) -> bool:
    """
    Supports the structured weekly availability generated by
    Module 4 while remaining tolerant of small naming differences.

    Supported examples:

    {
        "monday": {
            "enabled": true,
            "start_time": "09:00",
            "end_time": "17:00"
        }
    }

    or:

    {
        "monday": {
            "enabled": true,
            "start": "09:00",
            "end": "17:00"
        }
    }
    """

    if not availability:
        return False

    day = get_day_name(appointment_date)

    if isinstance(availability, dict):
        day_config = availability.get(day)

        if day_config is None:
            day_config = availability.get(day.capitalize())

        if day_config is None:
            return False

    elif isinstance(availability, list):
        day_config = None

        for item in availability:
            if not isinstance(item, dict):
                continue

            item_day = str(
                item.get("day", "")
            ).lower()

            if item_day == day:
                day_config = item
                break

        if day_config is None:
            return False

    else:
        return False

    if isinstance(day_config, list):
        ranges = day_config
    else:
        ranges = [day_config]

    selected_time = parse_time(appointment_time)

    for period in ranges:
        if not isinstance(period, dict):
            continue

        enabled = period.get("enabled", True)

        if enabled is False:
            continue

        start_value = (
            period.get("start_time")
            or period.get("start")
            or period.get("from")
        )

        end_value = (
            period.get("end_time")
            or period.get("end")
            or period.get("to")
        )

        if not start_value or not end_value:
            continue

        try:
            start_time = datetime.strptime(
                str(start_value),
                "%H:%M",
            ).time()

            end_time = datetime.strptime(
                str(end_value),
                "%H:%M",
            ).time()
        except ValueError:
            continue

        if start_time <= selected_time < end_time:
            return True

    return False


async def get_doctor(doctor_id: str) -> Optional[dict]:
    db = get_database()

    try:
        return await db["doctors"].find_one(
            {"_id": ObjectId(doctor_id)}
        )
    except Exception:
        return None


async def get_patient_for_user(
    user_id: str,
) -> Optional[dict]:
    return await PatientModel.get_by_user_id(user_id)


async def build_response(
    appointment: dict,
) -> AppointmentResponse:
    doctor = await get_doctor(
        appointment["doctor_id"]
    )

    return AppointmentResponse(
        **serialize_appointment(
            appointment,
            doctor,
        )
    )


@router.post(
    "",
    response_model=AppointmentResponse,
    status_code=status.HTTP_201_CREATED,
)
async def create_appointment(
    payload: AppointmentCreate,
    current_user: UserResponse = Depends(require_patient),
):
    patient = await get_patient_for_user(
        current_user.id
    )

    if not patient:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Patient profile not found. Please complete your profile first.",
        )

    doctor = await get_doctor(payload.doctor_id)

    if not doctor:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Doctor not found.",
        )

    if doctor.get("verification_status") != "approved":
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="This doctor is not currently available for consultations.",
        )

    if payload.appointment_date < date.today():
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Appointment date must be today or a future date.",
        )

    selected_time = parse_time(
        payload.appointment_time
    )

    if payload.appointment_date == date.today():
        now = datetime.now().time()

        if selected_time <= now:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Appointment time must be in the future.",
            )

    if not availability_allows_slot(
        doctor.get("availability"),
        payload.appointment_date,
        payload.appointment_time,
    ):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="The selected time is outside the doctor's availability.",
        )

    patient_id = str(patient["_id"])

    if await AppointmentModel.slot_is_taken(
        doctor_id=payload.doctor_id,
        appointment_date=payload.appointment_date,
        appointment_time=payload.appointment_time,
    ):
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="This appointment slot has already been booked.",
        )

    appointment_data = {
        "patient_id": patient_id,
        "doctor_id": payload.doctor_id,
        "appointment_date": payload.appointment_date,
        "appointment_time": payload.appointment_time,
        "mode": payload.mode.value,
        "reason": payload.reason,
        "status": AppointmentStatus.pending.value,
    }

    try:
        appointment = await AppointmentModel.create(
            appointment_data
        )
    except DuplicateKeyError:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="This appointment slot has already been booked.",
        )

    return await build_response(appointment)


@router.get(
    "",
    response_model=AppointmentListResponse,
)
async def get_appointments(
    current_user: UserResponse = Depends(
        get_current_user
    ),
    appointment_status: Optional[str] = Query(
        default=None,
        alias="status",
    ),
):
    if current_user.role == "patient":
        patient = await get_patient_for_user(
            current_user.id
        )

        if not patient:
            return AppointmentListResponse(
                appointments=[]
            )

        appointments = (
            await AppointmentModel.get_by_patient(
                str(patient["_id"])
            )
        )

    elif current_user.role == "doctor":
        db = get_database()

        doctor = await db["doctors"].find_one(
            {"user_id": current_user.id}
        )

        if not doctor:
            return AppointmentListResponse(
                appointments=[]
            )

        appointments = (
            await AppointmentModel.get_by_doctor(
                str(doctor["_id"])
            )
        )

    else:
        db = get_database()

        cursor = db["appointments"].find({}).sort(
            [
                ("appointment_date", 1),
                ("appointment_time", 1),
            ]
        )

        appointments = await cursor.to_list(
            length=1000
        )

    if appointment_status:
        appointments = [
            item
            for item in appointments
            if item.get("status")
            == appointment_status
        ]

    responses = []

    for appointment in appointments:
        responses.append(
            await build_response(appointment)
        )

    return AppointmentListResponse(
        appointments=responses
    )


